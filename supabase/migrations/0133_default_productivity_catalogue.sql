COMMENT ON FUNCTION public.seed_default_productivity_rules(uuid) IS
  'Seeds the default productive/neutral catalogue for one organisation. '
  'Idempotent and non-destructive: existing rules for the same pattern are '
  'left untouched, so it is safe to re-run after the catalogue grows.';

-- Backfill every organisation that exists today.
DO $do$
DECLARE r record; n integer; total integer := 0;
BEGIN
  FOR r IN SELECT id FROM public.organizations LOOP
    SELECT public.seed_default_productivity_rules(r.id) INTO n;
    total := total + n;
  END LOOP;
  RAISE NOTICE 'seeded % default productivity rules across all organisations', total;
END $do$;

-- And every organisation created from now on, so a new customer is never left
-- with a blank ruleset. AFTER INSERT so a failure here cannot roll back the
-- signup itself.
CREATE OR REPLACE FUNCTION public.tg_seed_org_productivity_rules()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $tg$
BEGIN
  PERFORM public.seed_default_productivity_rules(NEW.id);
  RETURN NULL;
EXCEPTION WHEN OTHERS THEN
  -- Seeding defaults is a convenience, not a precondition for having an
  -- account. Log and carry on rather than failing organisation creation.
  RAISE WARNING 'could not seed default productivity rules for org %: %', NEW.id, SQLERRM;
  RETURN NULL;
END
$tg$;

DROP TRIGGER IF EXISTS trg_seed_org_productivity_rules ON public.organizations;
CREATE TRIGGER trg_seed_org_productivity_rules
  AFTER INSERT ON public.organizations
  FOR EACH ROW EXECUTE FUNCTION public.tg_seed_org_productivity_rules();

