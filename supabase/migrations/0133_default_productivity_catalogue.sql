-- Default productivity catalogue.
--
-- Until now a new organisation started with an empty productivity_rules table,
-- so every application and site was uncategorised and the productivity figure
-- was computed from nothing. Migration 0118 already fixed one version of this
-- problem ("sabki 50% aa rhi hai" — every agent showing 50%) by excluding
-- uncategorised time from the ratio; the honest consequence was that an org
-- with no rules simply showed no productivity at all.
--
-- This seeds a catalogue of 899 rules so productivity means something on day
-- one, and so an admin has a list to edit rather than a blank page.
--
-- POLICY MODEL (chosen deliberately): everything in this catalogue is
-- productive; anything an employee touches that is NOT here is unproductive.
-- Migration 0134 implements the second half in the scoring functions. That is
-- why there is not a single 'unproductive' row below — under this model an
-- explicit unproductive list would be redundant, and hundreds of rows of
-- blocked domains would obscure the rules that actually carry information.
--
-- The exception is 'neutral', which means "do not count this either way" and
-- is load-bearing here for two groups that would otherwise be scored against
-- the employee unfairly:
--
--   * OS shell and system processes. The lock screen, Start menu, file
--     pickers, the IME host and the window manager all reach the foreground
--     without anyone choosing them.
--   * Browsers themselves, and search engines and webmail. A browser process
--     is a container — what matters is the site, which host rules classify. And
--     a search engine is genuinely both: nearly all research passes through
--     one, as does nearly all time-wasting.
--
-- Rules are seeded per organisation with department = NULL, i.e. as the
-- org-wide default. Admins can retune anything in Admin Portal → Applications,
-- including adding department overrides (see 0129) such as YouTube being
-- productive for a Content team.

